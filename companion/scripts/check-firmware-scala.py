#!/usr/bin/env python3
"""Check the firmware's Scala (mapped) output against the companion's.

In Scala mode the board sends each key as a channel and a note, worked out from
three integers the companion sends in an 'O' frame. This extracts
`output_params_t`, `mapped_channel`, `mapped_for_xy` and `output_params_apply`
VERBATIM from Core/Src/main.c, compiles them with clang, feeds them real 'O'
frames built by the companion's own `outputFrame`, and diffs every key of a
four-board grid against the companion's `scalaNote` — over EDOs from 5 to 72,
all three layouts, all six rotations and two anchors. It also checks that
malformed frames are refused.

Run with `npm run check:scala`. Needs clang and node; it writes only into a
temporary directory.
"""

from __future__ import annotations

import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
COMPANION = HERE.parent
MAIN_C = COMPANION.parent / "Core" / "Src" / "main.c"
BOARDS = 4


def grab(src: str, sig: str) -> str:
    """The brace-balanced declaration starting at `sig` (to its `;` for a typedef or initialiser)."""
    i = src.index(sig)
    k = src.index("{", i)
    depth = 0
    while True:
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    needs_semicolon = src[i:k].lstrip().startswith(("typedef", "static volatile", "static const"))
    return src[i : (src.index(";", k) + 1) if needs_semicolon else (k + 1)]


REFERENCE_MJS = """
const { readFileSync } = await import("node:fs");
const { pathToFileURL } = await import("node:url");
const lib = (f) => pathToFileURL(`${process.argv[3]}/src/lib/${f}`).href;
const { scalaMap, scalaNote, outputFrame } = await import(lib("scala.ts"));
const { defaultPitchMap } = await import(lib("tuning.ts"));
const { LED_POS } = await import(lib("layout.ts"));
const { configs, boards } = JSON.parse(readFileSync(process.argv[2], "utf8"));
const hex2 = (n) => n.toString(16).padStart(2, "0");
const out = [];
configs.forEach((cfg, i) => {
  const g = { ...defaultPitchMap().generator, ...cfg };
  const map = scalaMap(g);
  out.push(`FRAME ${i} ` + [...outputFrame(map).slice(1)].map(hex2).join(""));
  for (let b = 0; b < boards; b++) for (const [lx, ly] of LED_POS) {
    const x = lx + 5 * b, y = ly + 2 * b;
    const n = scalaNote(map, x, y);
    out.push(`ROW ${i} ${x} ${y} ` + (n ? `${n.channel - 1} ${n.note}` : "- -"));
  }
});
console.log(out.join("\\n"));
"""


def build_harness(src: str, led_pos: list[list[int]]) -> str:
    defines = "\n".join(l for l in src.splitlines() if re.match(r"#define OUTPUT_", l))
    params = grab(src, "typedef struct {\n  uint8_t mode;")
    decl = grab(src, "static volatile output_params_t output_params =")
    channel = grab(src, "static uint8_t mapped_channel(int32_t bank)")
    mapped = grab(src, "static uint8_t mapped_for_xy(int32_t x, int32_t y,")
    apply_fn = grab(src, "static uint8_t output_params_apply(const uint8_t *m)")
    pos = ",".join(f"{{{x},{y}}}" for x, y in led_pos)
    return f"""/* GENERATED by check-firmware-scala.py from Core/Src/main.c. Do not edit. */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
{defines}
{params}
{decl}
{channel}
{mapped}
{apply_fn}

static const int LED_POS[{len(led_pos)}][2] = {{ {pos} }};
#define NKEYS ((int)(sizeof(LED_POS)/sizeof(LED_POS[0])))

int main(void)
{{
  uint8_t m[OUTPUT_MSG_LEN];
  #define PUT16(i, v) do {{ m[i] = (uint8_t)(v); m[(i)+1] = (uint8_t)((uint16_t)(v) >> 8); }} while (0)
  memset(m, 0, sizeof(m)); m[0] = 2;            printf("REJECT mode %d\\n", !output_params_apply(m));
  memset(m, 0, sizeof(m)); m[0] = 1; PUT16(1, OUTPUT_STEP_MAX + 1);
                                                printf("REJECT step_a %d\\n", !output_params_apply(m));
  memset(m, 0, sizeof(m)); m[0] = 1; PUT16(3, -OUTPUT_STEP_MAX - 1);
                                                printf("REJECT step_b %d\\n", !output_params_apply(m));
  memset(m, 0, sizeof(m)); m[0] = 1; PUT16(1, 5); PUT16(3, 3); PUT16(5, 65);
                                                printf("REJECT none %d\\n", output_params_apply(m));

  char hex[256];
  int cfg = 0;
  while (fgets(hex, sizeof(hex), stdin)) {{
    if (hex[0] == '\\n' || hex[0] == '\\0') continue;
    for (int i = 0; i < OUTPUT_MSG_LEN; i++) {{
      unsigned byte = 0;
      sscanf(hex + i * 2, "%2x", &byte);
      m[i] = (uint8_t)byte;
    }}
    if (!output_params_apply(m)) {{ printf("ROW %d rejected\\n", cfg++); continue; }}
    for (int b = 0; b < {BOARDS}; b++) for (int k = 0; k < NKEYS; k++) {{
      int32_t x = LED_POS[k][0] + 5 * b, y = LED_POS[k][1] + 2 * b;
      uint8_t ch, note;
      if (mapped_for_xy(x, y, &ch, &note)) printf("ROW %d %ld %ld %u %u\\n", cfg, (long)x, (long)y, ch, note);
      else printf("ROW %d %ld %ld - -\\n", cfg, (long)x, (long)y);
    }}
    cfg++;
  }}
  return 0;
}}
"""


def configs() -> list[dict]:
    out = []
    for edo in (5, 7, 12, 17, 19, 22, 31, 41, 53, 72):
        for layout in ("bosanquet", "wicki-hayden", "harmonic-table"):
            for rotation in range(6):
                for note, key in (("D4", [3, 3]), ("C1", [0, 6])):
                    out.append({"tuning": {"kind": "edo", "edo": edo}, "layout": layout,
                                "rotation": rotation, "anchorNote": note, "anchorKey": key})
    return out


def main() -> int:
    if not shutil.which("clang"):
        sys.exit("clang not found")
    src = MAIN_C.read_text()
    cfgs = configs()
    led_pos = json.loads(subprocess.run(
        ["node", "--import", str(HERE / "ts-resolve.mjs"), "-e",
         'const {LED_POS} = await import("./src/lib/layout.ts"); console.log(JSON.stringify(LED_POS));'],
        cwd=COMPANION, capture_output=True, text=True, check=True).stdout)

    with tempfile.TemporaryDirectory() as tmp:
        tmpd = pathlib.Path(tmp)
        (tmpd / "reference.mjs").write_text(REFERENCE_MJS)
        (tmpd / "payload.json").write_text(json.dumps({"configs": cfgs, "boards": BOARDS}))
        ref = subprocess.run(
            ["node", "--import", str(HERE / "ts-resolve.mjs"), str(tmpd / "reference.mjs"),
             str(tmpd / "payload.json"), str(COMPANION)],
            cwd=COMPANION, capture_output=True, text=True, check=True).stdout
        frames = [l.split()[2] for l in ref.splitlines() if l.startswith("FRAME")]
        (tmpd / "harness.c").write_text(build_harness(src, led_pos))
        subprocess.run(["clang", "-O2", "-Wall", "-Wextra", "-Werror", "-o", str(tmpd / "harness"),
                        str(tmpd / "harness.c")], check=True)
        c_out = subprocess.run([str(tmpd / "harness")], input="\n".join(frames) + "\n",
                               capture_output=True, text=True, check=True).stdout

    failures = 0
    checked = 0
    for line in c_out.splitlines():
        if line.startswith("REJECT"):
            _, what, ok = line.split()
            checked += 1
            if ok != "1":
                failures += 1
                print(f"  FAIL  {'a valid frame was refused' if what == 'none' else f'a {what} frame was accepted'}")
    print(f"  validation accepts and refuses all {checked} frames as intended")

    c_rows = [l for l in c_out.splitlines() if l.startswith("ROW")]
    ref_rows = [l for l in ref.splitlines() if l.startswith("ROW")]
    if c_rows == ref_rows:
        print(f"  firmware channels and notes match the companion's on all {len(c_rows)} keys "
              f"({len(cfgs)} mappings x {len(led_pos) * BOARDS} keys)")
    else:
        failures += 1
        bad = [(a, b) for a, b in zip(c_rows, ref_rows) if a != b]
        print(f"  FAIL  {len(bad)} of {len(c_rows)} differ")
        for a, b in bad[:3]:
            print(f"          firmware:  {a}\n          companion: {b}")
    print("PASS" if failures == 0 else "FAIL")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
